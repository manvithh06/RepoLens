BINARY_EXTENSIONS = frozenset(
    {
        ".png", ".jpg", ".jpeg", ".gif", ".bmp", ".ico", ".webp", ".tiff", ".psd",
        ".pdf",
        ".zip", ".tar", ".gz", ".tgz", ".bz2", ".xz", ".7z", ".rar", ".jar", ".war",
        ".exe", ".dll", ".so", ".dylib", ".o", ".a", ".class", ".pyc", ".pyo", ".wasm",
        ".woff", ".woff2", ".ttf", ".otf", ".eot",
        ".mp3", ".mp4", ".mov", ".avi", ".wav", ".flac",
        ".sqlite", ".db", ".pkl", ".npy", ".parquet", ".bin", ".iso", ".dmg",
    }
)  # fmt: skip

GENERATED_SUFFIXES = (".min.js", ".min.css", ".map")
GENERATED_MARKERS = (
    b"@generated",
    b"Code generated",
    b"Generated by the protocol buffer compiler",
)

_HEAD_BYTES = 8192
_MARKER_WINDOW = 1024


@dataclass(frozen=True)
class KeptFile:
    path: str  # relative to the repository root, always with forward slashes
    size: int


@dataclass(frozen=True)
class FilterResult:
    files: list[KeptFile]
    skipped: dict[str, int]  # reason -> how many files or folders were skipped
    truncated: bool  # True if a limit stopped us from keeping everything


def _is_excluded_dir(name: str) -> bool:
    return name in EXCLUDED_DIRS or name.endswith(EXCLUDED_DIR_SUFFIXES)


def _is_inside(real_root: str, path: str) -> bool:
    try:
        return os.path.commonpath([real_root, os.path.realpath(path)]) == real_root
    except ValueError:
        return False


def _skip_reason(path: str, name: str, real_root: str) -> tuple[str | None, int]:
    """Return (reason, 0) if the file should be skipped, or (None, size) if we keep it."""
    lowered = name.lower()
    if lowered in LOCK_FILES:
        return "lock_file", 0
    if os.path.splitext(lowered)[1] in BINARY_EXTENSIONS:
        return "binary", 0
    if lowered.endswith(GENERATED_SUFFIXES):
        return "generated", 0

    try:
        info = os.lstat(path)
    except OSError:
        return "unreadable", 0
    if stat.S_ISLNK(info.st_mode):
        return "symlink", 0
    if not stat.S_ISREG(info.st_mode):
        return "special_file", 0
    if not _is_inside(real_root, path):
        return "outside_repository", 0
    if info.st_size > MAX_FILE_SIZE_BYTES:
        return "too_large", 0

    try:
        with open(path, "rb") as handle:
            head = handle.read(_HEAD_BYTES)
    except OSError:
        return "unreadable", 0
    if b"\0" in head:
        return "binary", 0
    if any(marker in head[:_MARKER_WINDOW] for marker in GENERATED_MARKERS):
        return "generated", 0
    return None, info.st_size


def filter_repository(root: Path) -> FilterResult:
    real_root = os.path.realpath(root)
    skipped: Counter[str] = Counter()
    candidates: list[KeptFile] = []
    seen = 0
    truncated = False

    for dirpath, dirnames, filenames in os.walk(real_root, followlinks=False):
        seen += 1
        if seen > MAX_WALK_ENTRIES:
            truncated = True
            break

        dirnames.sort()
        filenames.sort()

        kept_dirs: list[str] = []
        for name in dirnames:
            if os.path.islink(os.path.join(dirpath, name)):
                skipped["symlink"] += 1
            elif _is_excluded_dir(name):
                skipped["excluded_directory"] += 1
            else:
                kept_dirs.append(name)
        dirnames[:] = (
            kept_dirs  # changing this list in place stops os.walk entering skipped folders
        )

        for name in filenames:
            seen += 1
            if seen > MAX_WALK_ENTRIES:
                truncated = True
                break
            path = os.path.join(dirpath, name)
            reason, size = _skip_reason(path, name, real_root)
            if reason is not None:
                skipped[reason] += 1
                continue
            relative = os.path.relpath(path, real_root).replace(os.sep, "/")
            candidates.append(KeptFile(path=relative, size=size))

        if truncated:
            break

    # Shallow files first, so a root README or src/ file always beats a deeply nested one.
    candidates.sort(key=lambda kept: (kept.path.count("/"), kept.path))
    if len(candidates) > MAX_FILE_COUNT:
        skipped["file_limit"] += len(candidates) - MAX_FILE_COUNT
        candidates = candidates[:MAX_FILE_COUNT]
        truncated = True

    return FilterResult(files=candidates, skipped=dict(skipped), truncated=truncated)
