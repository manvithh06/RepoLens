import os
from pathlib import Path

import pytest

from app.core.limits import MAX_FILE_SIZE_BYTES
from app.services.acquisition import file_filter
from app.services.acquisition.file_filter import filter_repository


def _write(root: Path, relative: str, content: str | bytes = "x\n") -> None:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(content, bytes):
        path.write_bytes(content)
    else:
        path.write_text(content)


def _paths(root: Path) -> list[str]:
    return [kept.path for kept in filter_repository(root).files]


def test_keeps_normal_source_and_config_files(tmp_path: Path) -> None:
    for name in ("README.md", "src/app.py", "src/__init__.py", "package.json"):
        _write(tmp_path, name)
    _write(tmp_path, ".github/workflows/ci.yml")

    assert _paths(tmp_path) == [
        "README.md",
        "package.json",
        "src/__init__.py",
        "src/app.py",
        ".github/workflows/ci.yml",
    ]


def test_skips_dependency_build_and_cache_folders(tmp_path: Path) -> None:
    _write(tmp_path, "README.md")
    for folder in ("node_modules", ".git", "venv", "dist", "build", "__pycache__", "pkg.egg-info"):
        _write(tmp_path, f"{folder}/inner.txt")

    result = filter_repository(tmp_path)

    assert [kept.path for kept in result.files] == ["README.md"]
    assert result.skipped["excluded_directory"] == 7


def test_skips_lock_files_but_keeps_manifests(tmp_path: Path) -> None:
    for name in ("package.json", "package-lock.json", "poetry.lock", "yarn.lock", "go.sum"):
        _write(tmp_path, name)

    result = filter_repository(tmp_path)

    assert [kept.path for kept in result.files] == ["package.json"]
    assert result.skipped["lock_file"] == 4


def test_skips_binary_files_by_extension_and_by_content(tmp_path: Path) -> None:
    _write(tmp_path, "logo.png", b"not really a png")
    _write(tmp_path, "blob.dat", b"abc\x00def")
    _write(tmp_path, "notes.txt", "plain text")

    result = filter_repository(tmp_path)

    assert [kept.path for kept in result.files] == ["notes.txt"]
    assert result.skipped["binary"] == 2


def test_skips_files_over_the_size_limit(tmp_path: Path) -> None:
    _write(tmp_path, "big.txt", "a" * (MAX_FILE_SIZE_BYTES + 1))
    _write(tmp_path, "small.txt", "a")

    result = filter_repository(tmp_path)

    assert [kept.path for kept in result.files] == ["small.txt"]
    assert result.skipped["too_large"] == 1


def test_skips_generated_files(tmp_path: Path) -> None:
    _write(tmp_path, "app.min.js", "x")
    _write(tmp_path, "bundle.js.map", "{}")
    _write(tmp_path, "api.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n")
    _write(tmp_path, "schema.ts", "// @generated\nexport {}\n")
    _write(tmp_path, "main.py", "print('hand written')\n")

    result = filter_repository(tmp_path)

    assert [kept.path for kept in result.files] == ["main.py"]
    assert result.skipped["generated"] == 4


@pytest.mark.skipif(os.name == "nt", reason="symlinks need special rights on Windows")
def test_skips_symlinks_to_files_and_folders(tmp_path: Path) -> None:
    outside = tmp_path / "outside"
    outside.mkdir()
    (outside / "secret.txt").write_text("TOP SECRET")

    repo = tmp_path / "repo"
    _write(repo, "real.py")
    (repo / "link.txt").symlink_to(outside / "secret.txt")
    (repo / "linked_dir").symlink_to(outside, target_is_directory=True)

    result = filter_repository(repo)

    assert [kept.path for kept in result.files] == ["real.py"]
    assert result.skipped["symlink"] == 2


@pytest.mark.skipif(not hasattr(os, "mkfifo"), reason="needs named pipes")
def test_special_files_are_skipped_without_hanging(tmp_path: Path) -> None:
    _write(tmp_path, "real.py")
    os.mkfifo(tmp_path / "pipe")

    result = filter_repository(tmp_path)

    assert [kept.path for kept in result.files] == ["real.py"]
    assert result.skipped["special_file"] == 1


def test_shallow_files_come_first_and_paths_use_forward_slashes(tmp_path: Path) -> None:
    _write(tmp_path, "a/b/c/deep.py")
    _write(tmp_path, "z.py")
    _write(tmp_path, "a/mid.py")

    assert _paths(tmp_path) == ["z.py", "a/mid.py", "a/b/c/deep.py"]


def test_file_count_limit_keeps_the_shallowest_files(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(file_filter, "MAX_FILE_COUNT", 3)
    for name in ("a.py", "b.py", "src/c.py", "src/d.py", "src/deep/e.py"):
        _write(tmp_path, name)

    result = filter_repository(tmp_path)

    assert [kept.path for kept in result.files] == ["a.py", "b.py", "src/c.py"]
    assert result.truncated is True
    assert result.skipped["file_limit"] == 2


def test_walk_limit_stops_a_huge_repository(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(file_filter, "MAX_WALK_ENTRIES", 3)
    for index in range(10):
        _write(tmp_path, f"file{index}.py")

    result = filter_repository(tmp_path)

    assert result.truncated is True
    assert len(result.files) < 10